/**
 * SkillCatalog.ts
 *
 * Catálogo de skills pré-prontas que podem ser ativadas por agente.
 * Cada entrada é um template: ao "ativar" no frontend, uma Skill real
 * (model Skill) é criada para o agente com metadata.catalogKey = key,
 * e passa a ser injetada no prompt via skillCache/CustomSkillPrompt.
 *
 * O campo `description` é o texto de instrução injetado no prompt —
 * por isso cada skill traz o comportamento completo, não só um resumo.
 */

export interface CatalogSkill {
  key: string;
  name: string;
  category: string;
  description: string; // instrução injetada no prompt ao ativar
  triggers: { type: string; value: string; weight?: number }[];
  functions: string[];
  priority: number;
}

// Helper compacto para declarar as skills do catálogo
const S = (
  key: string,
  name: string,
  category: string,
  description: string,
  keywords: string[],
  functions: string[] = [],
  priority = 6
): CatalogSkill => ({
  key,
  name,
  category,
  description,
  triggers: keywords.map(k => ({ type: "keyword", value: k, weight: 0.7 })),
  functions,
  priority
});

